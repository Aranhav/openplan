/// An item as a list shows it, from the fields the engine keeps.
fn item_dto(id: ItemId, code: Option<&str>, name: &str, parent: Option<ItemId>) -> ItemDto {
    ItemDto {
        id: id.0,
        code: code.map(str::to_string),
        name: name.to_string(),
        parent_id: parent.map(|parent| parent.0),
    }
}

fn item_ids(ids: Vec<Uuid>) -> Vec<ItemId> {
    ids.into_iter().map(ItemId).collect()
}

fn uuids(ids: &[ItemId]) -> Vec<Uuid> {
    ids.iter().map(|id| id.0).collect()
}

/// A refusal of a request body that names something the model does not have.
fn missing(field: &str, message: &str) -> AppError {
    AppError::MissingReferences(vec![FieldError {
        field: field.to_string(),
        message: message.to_string(),
    }])
}

/// The same error about another field, such as an entry of a list in the request.
fn on_field(mut error: FieldError, field: String) -> FieldError {
    error.field = field;
    error
}

/// Fails unless `value` lies in `range`; `what` names the value in the message.
fn within<T>(field: &str, what: &str, value: T, range: RangeInclusive<T>) -> Result<(), FieldError>
where
    T: PartialOrd + Copy + std::fmt::Display,
{
    if range.contains(&value) {
        return Ok(());
    }
    Err(FieldError {
        field: field.to_string(),
        message: format!(
            "{what} must be between {} and {}.",
            range.start(),
            range.end()
        ),
    })
}

/// The month a label such as `Jan 26` names. Anything else, including a month outside the
/// calendar, is refused on `field`.
fn month_of(calendar: &EngineCalendar, label: &str, field: &str) -> Result<u32, FieldError> {
    match calendar.parse_label(label) {
        Some((TimeLevel::Month, month)) => Ok(month),
        _ => Err(FieldError {
            field: field.to_string(),
            message: format!(
                "{} must be a month of the calendar, such as Jan 26.",
                validate::label(field)
            ),
        }),
    }
}

/// Fails with `MissingReferences`, naming each field, for the items that are not live items of
/// `list`. `message` says what is missing.
fn ensure_items(
    list: &List,
    message: &str,
    items: impl Iterator<Item = (String, ItemId)>,
) -> AppResult<()> {
    let missing: Vec<FieldError> = items
        .filter(|(_, item)| list.idx(*item).is_none())
        .map(|(field, _)| FieldError {
            field,
            message: message.to_string(),
        })
        .collect();
    if missing.is_empty() {
        Ok(())
    } else {
        Err(AppError::MissingReferences(missing))
    }
}

/// The parents that items name must be items of the parent list, when the list has one.
fn ensure_parents(
    structure: &Structure,
    list: &List,
    parents: impl Iterator<Item = (String, ItemId)>,
) -> AppResult<()> {
    match list.parent.and_then(|parent| structure.list(parent)) {
        Some(parent_list) => ensure_items(
            parent_list,
            "The parent item does not exist in the parent list.",
            parents,
        ),
        None => Ok(()),
    }
}

/// Applies the change that `build` makes from the model, in the actor, and answers 204.
async fn delete_with(
    state: &AppState,
    user: &CurrentUser,
    model_id: Uuid,
    build: impl FnOnce(&Model) -> AppResult<Vec<Command>> + Send + 'static,
) -> AppResult<StatusCode> {
    let handle = handle_for(
        state,
        user,
        model_id,
        WorkspaceRole::Builder,
        ProdLock::Enforce,
    )
    .await?;
    handle.apply_with(user.id, build).await?;
    Ok(StatusCode::NO_CONTENT)
}

/// The model's row: its workspace and mode. `NotFound` when there is no such model.
async fn model_row(db: &PgPool, model_id: Uuid) -> AppResult<(Uuid, ModelMode)> {
    sqlx::query_as::<_, (Uuid, ModelMode)>("SELECT workspace_id, mode FROM models WHERE id = $1")
        .bind(model_id)
        .fetch_optional(db)
        .await?
        .ok_or(AppError::NotFound)
}

/// Whether a model in production mode refuses the change a handler is about to make.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum ProdLock {
    /// The change is to the structure, which a production model takes through ALM sync only.
    Enforce,
    /// The change is to the data, or there is none.
    Ignore,
}

/// The model's actor, for a caller whose role in the model's workspace is at least `min_role`:
/// `NotFound` when they are not a member of it, `Forbidden` when their role is below `min_role`,
/// and, if `lock` is `Enforce`, `model.production_locked` when the model is in production mode.
/// Every handler gets the actor from here, before it reads anything else of the request, so that
/// none skips the role or the lock.
pub(crate) async fn handle_for(
    state: &AppState,
    user: &CurrentUser,
    model_id: Uuid,
    min_role: WorkspaceRole,
    lock: ProdLock,
) -> AppResult<ModelHandle> {
    access_for(state, user, model_id, min_role, lock)
        .await
        .map(|(handle, _)| handle)
}

/// [`handle_for`], with the caller's role in the model's workspace as well, for a handler that
/// shows what that role may do.
async fn access_for(
    state: &AppState,
    user: &CurrentUser,
    model_id: Uuid,
    min_role: WorkspaceRole,
    lock: ProdLock,
) -> AppResult<(ModelHandle, WorkspaceRole)> {
    let (workspace_id, mode) = model_row(&state.db, model_id).await?;
    let role = require_workspace_role(&state.db, user, workspace_id, min_role).await?;
    if lock == ProdLock::Enforce && mode == ModelMode::Prod {
        return Err(AppError::Conflict {
            code: "model.production_locked",
            detail: PRODUCTION_LOCKED.into(),
        });
    }
    Ok((state.models.get(model_id).await?, role))
}

/// The actor of the model and the caller's role, for a caller who may read the model. It is taken
/// from the head of the request, ahead of the body, so that a caller who may not read the model is
/// refused without the body, which may be megabytes, being read.
pub(crate) struct Viewer {
    pub(crate) handle: ModelHandle,
    pub(crate) role: WorkspaceRole,
}

impl FromRequestParts<AppState> for Viewer {
    type Rejection = AppError;

    async fn from_request_parts(parts: &mut Parts, state: &AppState) -> AppResult<Viewer> {
        let user = CurrentUser::from_request_parts(parts, state).await?;
        let ApiPath(model_id) = ApiPath::<Uuid>::from_request_parts(parts, state).await?;
        let (handle, role) = access_for(
            state,
            &user,
            model_id,
            WorkspaceRole::Viewer,
            ProdLock::Ignore,
        )
        .await?;
        Ok(Viewer { handle, role })
    }
}

/// Stores the version `id` as the request says, inside the actor, against the calendar the model
/// holds then, and returns it as the model now holds it.
async fn store_version(
    handle: &ModelHandle,
    user_id: Uuid,
    id: VersionId,
    body: VersionRequest,
) -> AppResult<VersionDto> {
    let name = validate::entity_name("name", &body.name)?;
    let switchover_label = body.switchover;
    let (is_actual, is_current) = (body.is_actual, body.is_current);
    handle
        .apply_with_answer(user_id, move |model| {
            let calendar = model.structure().calendar;
            let switchover = switchover_label
                .as_deref()
                .map(|label| month_of(&calendar, label, "switchover"))
                .transpose()?;
            let version = VersionDto {
                id: id.0,
                name: name.clone(),
                is_actual,
                is_current,
                switchover: switchover.map(|month| calendar.label(TimeLevel::Month, month)),
            };
            let command = Command::UpsertVersion {
                id,
                name,
                is_actual,
                is_current,
                switchover,
            };
            Ok((vec![command], version))
        })
        .await
}

